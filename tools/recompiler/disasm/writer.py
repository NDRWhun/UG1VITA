"""Writes the generated C++ module of the game executable.

<name>.h            class Application: constructor and execute()
<name>.cpp          constructor: method registration, import shims; execute()
<name>.<start>.cpp  the functions whose entries lie in one guest address bucket [start, start + BUCKET)
<name>_layout.h     guest layout and identity of the executable (sections, hash) for the runtime

Each guest function is a free function nfsu::sub_<address>(app, cpu). A bucket file declares only the functions it
references, so adding or removing a function changes its own bucket, the files that call it and <name>.cpp.

The executable's bytes are not part of the output: the runtime loads the user's file and checks its hash.
"""

import hashlib
import io
import os
import re

from . import emit

# Bucket size in guest bytes: about 60 functions per file on average for Speed.exe.
BUCKET = 0x3000

PARAMETERS = '(win32::WinApplication* app, x86::CPU& cpu)'
REFERENCE = re.compile(r'\b(sub_[0-9a-f]+(?:_guest)?)\(app, cpu\)')
DEFINITION = re.compile(r'^void (sub_[0-9a-f]+(?:_guest)?)\(', re.M)


def cpp_name(import_name):
    """C++ name of an imported function: '_IFCreateEffects@12' -> 'IFCreateEffects'."""
    return re.sub(r'^_|@\d+$', '', import_name)


def bucket_of(address):
    """Start address of the bucket holding a function entry."""
    return address - address % BUCKET


def bucket_file(module_name, start):
    return '%s.%08x.cpp' % (module_name, start)


class Writer:
    def __init__(self, module, program, out_dir, function_names=None):
        self.module = module
        self.program = program
        self.out_dir = out_dir
        self.function_names = function_names or {}
        self.name = module.application_name

    def path(self, file_name):
        return os.path.join(self.out_dir, file_name)

    def function_name(self, address):
        return self.function_names.get(address, 'sub_%x' % address)

    def write(self):
        self.write_layout()
        functions = [self.program.functions[s.get_entry_point()] for s in self.module.subroutines]
        buckets = {}
        for fn in functions:
            buckets.setdefault(bucket_of(fn.entry_address), []).append(fn)
        for start, members in sorted(buckets.items()):
            self.write_bucket(start, sorted(members, key=lambda fn: fn.entry_address))
        guard = '%s_H_' % self.name.upper()
        with open(self.path('%s.h' % self.name), 'w', newline='\n') as h:
            h.write('// Generated by tools/recompiler: the recompiled game executable.\n'
                    '#ifndef %s\n#define %s\n#include <x86.h>\n#include <lib/winapp.h>\n\n'
                    'namespace %s\n{\n\n'
                    'class Application : public win32::WinApplication\n{\npublic:\n'
                    '    // sections: the executable\'s sections, loaded at their guest addresses.\n'
                    '    Application(const char* appName, const std::vector<win32::Section>& sections);\n'
                    '    void execute();\n};\n\n}\n\n#endif /* !%s */\n' % (guard, guard, self.name, guard))
        self.write_registration(functions)

    def write_bucket(self, start, functions):
        body = io.StringIO()
        for fn in functions:
            emit.write_entry(body, io.StringIO(), self.module, self.program, fn,
                             self.function_name(fn.entry_address), '', '', 'win32::WinApplication',
                             self.function_names)
        text = body.getvalue()
        referenced = sorted(set(REFERENCE.findall(text)))
        with open(self.path(bucket_file(self.name, start)), 'w', newline='\n') as out:
            out.write('// Generated by tools/recompiler: guest functions 0x%08x-0x%08x.\n'
                      '#include <x86.h>\n#include <lib/winapp.h>\n#include <lib/thread.h>\n#include <recomp.h>\n'
                      '#include <native.h>\n\nnamespace %s\n{\n\n' % (start, start + BUCKET - 1, self.name))
            for name in referenced:
                out.write('void %s%s;\n' % (name, PARAMETERS))
            out.write('\n')
            out.write(text)
            out.write('}\n')

    def write_registration(self, functions):
        imports = self.module.image.imports
        dlls = sorted(set(i.dll for i in imports))
        with open(self.path('%s.cpp' % self.name), 'w', newline='\n') as src:
            src.write('// Generated by tools/recompiler: method registration and import binding.\n'
                      '#include "%s.h"\n#include "%s_layout.h"\n#include <winapi/wrapper.h>\n' % (self.name, self.name))
            for dll in dlls:
                src.write('#include <winapi/%s.h>\n' % dll)
            src.write('\nnamespace %s\n{\n\n' % self.name)
            for fn in functions:
                src.write('void %s%s;\n' % (self.function_name(fn.entry_address), PARAMETERS))
            src.write('\nApplication::Application(const char* appName, const std::vector<win32::Section>& sections)\n'
                      '    :   WinApplication(appName, layout::imageBase, sections)\n{\n')
            src.write('    reserveMethods(%d);\n' % (len(functions) + len(imports)))
            src.write('    // Imports: the import address table slots point at fake addresses with the shims behind them.\n')
            for i in imports:
                function = 'win32::%s::%s' % (i.dll, cpp_name(i.name))
                src.write('    getMemory<x86::reg32>(0x%08x) = 0x%08x;\n' % (i.iat_address, i.fake_address))
                src.write('    registerMethod(0x%08x, {"<%s>%s", &win32::Wrapper<decltype(&%s), &%s>::stdcall});\n'
                          % (i.fake_address, i.dll, i.name, function, function))
            # Indirect call targets first: they take the home slots of the method table.
            taken = self.program.address_taken
            for fn in [f for f in functions if f.entry_address in taken] + \
                    [f for f in functions if f.entry_address not in taken]:
                name = self.function_name(fn.entry_address)
                src.write('    registerMethod(0x%08x, {"%s", &%s});\n' % (fn.entry_address, name, name))
            src.write('}\n\nvoid Application::execute()\n{\n    runThread(m_cpu, 0x%x);\n}\n\n}\n'
                      % self.module.entry_point)

    def write_layout(self):
        image = self.module.image
        guard = '%s_LAYOUT_H_' % self.name.upper()
        resources = [s for s in image.sections if s.name == '.rsrc']
        lines = ['// Generated by tools/recompiler: guest layout and identity of the game executable.',
                 '#ifndef %s' % guard, '#define %s' % guard, '#include <x86.h>', '',
                 'namespace %s { namespace layout {' % self.name, '',
                 '// The executable the code was generated from.',
                 'constexpr const char* exeSha256 = "%s";' % image.sha256,
                 'constexpr x86::reg32 exeSize = %d;' % len(image.file_bytes), '',
                 'constexpr x86::reg32 imageBase = 0x%x;' % image.base,
                 'constexpr x86::reg32 headerSize = 0x%x;' % image.header_size,
                 'constexpr x86::reg32 entryPoint = 0x%x;' % image.entry_point,
                 '// End of the highest section; the guest heap starts above it.',
                 'constexpr x86::reg32 imageEnd = 0x%x;' % image.end_address(),
                 'constexpr x86::reg32 resourceSection = 0x%x;' % (resources[0].address if resources else 0), '',
                 'struct ImageSection',
                 '{',
                 '    const char* name;',
                 '    x86::reg32  address;',
                 '    x86::reg32  virtualSize;',
                 '    x86::reg32  fileOffset;     // raw data in the file',
                 '    x86::reg32  rawSize;',
                 '    const char* sha256;         // SHA-256 of the raw data; empty for code',
                 '};', '',
                 'constexpr ImageSection sections[] = {']
        for s in image.sections:
            digest = '' if s.code else hashlib.sha256(s.data).hexdigest()
            lines.append('    { "%s", 0x%x, 0x%x, 0x%x, 0x%x, "%s" },' % (s.name, s.address, s.virtual_size,
                                                                          s.file_offset, s.raw_size, digest))
        lines += ['};', '',
                  '// Functions whose callers read flags after they return, and those flags (cf 1, pf 2, af 4, zf 8, '
                  'sf 16,',
                  '// of 32, x87 condition codes 64). Sorted by address.',
                  'struct FlagReturn',
                  '{',
                  '    x86::reg32  address;',
                  '    x86::reg8   flags;',
                  '};', '',
                  'constexpr FlagReturn flagReturns[] = {']
        flag_mask = (1 << 7) - 1
        returns = sorted((a, m & flag_mask) for a, m in self.program.ret_live.items() if m & flag_mask)
        for a, m in returns:
            lines.append('    { 0x%x, 0x%x },' % (a, m))
        if not returns:
            lines.append('    { 0, 0 },')
        lines += ['};', 'constexpr x86::reg32 flagReturnCount = %d;' % len(returns), '',
                  '// The native overrides: the registers their callers read from cpu after they return (eax 1, ecx 2,',
                  '// edx 4, ebx 8, esp 16, ebp 32, esi 64, edi 128). The translated guest bodies store only these at',
                  '// their returns. Sorted by address.',
                  'struct RegisterReturn',
                  '{',
                  '    x86::reg32  address;',
                  '    x86::reg8   registers;',
                  '};', '',
                  'constexpr RegisterReturn registerReturns[] = {']
        overrides = sorted(a for a in self.program.native_overrides if a in self.program.ret_live)
        for a in overrides:
            lines.append('    { 0x%x, 0x%x },' % (a, (self.program.ret_live[a] >> 8) & 0xff))
        if not overrides:
            lines.append('    { 0, 0 },')
        lines += ['};', 'constexpr x86::reg32 registerReturnCount = %d;' % len(overrides), '',
                  '}}', '', '#endif /* !%s */' % guard, '']
        with open(self.path('%s_layout.h' % self.name), 'w', newline='\n') as f:
            f.write('\n'.join(lines))
