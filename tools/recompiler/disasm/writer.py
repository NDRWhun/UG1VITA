"""Writes the generated C++ module of the game executable.

<name>.h          class Application: one static method per guest function
<name>.cpp        constructor: method registration, import shims; execute()
<name>.<n>.cpp    the functions, FUNCTIONS_PER_FILE per file
<name>_layout.h   guest layout and identity of the executable (sections, hash) for the runtime

The executable's bytes are not part of the output: the runtime loads the user's file and checks its hash.
"""

import os
import re

from . import emit

FUNCTIONS_PER_FILE = 60


def cpp_name(import_name):
    """C++ name of an imported function: '_IFCreateEffects@12' -> 'IFCreateEffects'."""
    return re.sub(r'^_|@\d+$', '', import_name)


class Writer:
    def __init__(self, module, program, out_dir, function_names=None):
        self.module = module
        self.program = program
        self.out_dir = out_dir
        self.function_names = function_names or {}
        self.name = module.application_name

    def path(self, file_name):
        return os.path.join(self.out_dir, file_name)

    def function_name(self, address):
        return self.function_names.get(address, 'sub_%x' % address)

    def write(self):
        self.write_layout()
        functions = [self.program.functions[s.get_entry_point()] for s in self.module.subroutines]
        with open(self.path('%s.h' % self.name), 'w', newline='\n') as h:
            guard = '%s_H_' % self.name.upper()
            h.write('// Generated by tools/recompiler: the recompiled functions of the game executable.\n'
                    '#ifndef %s\n#define %s\n#include <x86.h>\n#include <lib/winapp.h>\n\n'
                    'namespace %s\n{\n\n'
                    'class Application : public win32::WinApplication\n{\npublic:\n'
                    '    // sections: the executable\'s sections, loaded at their guest addresses.\n'
                    '    Application(const char* appName, const std::vector<win32::Section>& sections);\n'
                    '    void execute();\n\n' % (guard, guard, self.name))
            for index in range(0, len(functions), FUNCTIONS_PER_FILE):
                file_name = '%s.%d.cpp' % (self.name, index // FUNCTIONS_PER_FILE)
                with open(self.path(file_name), 'w', newline='\n') as out:
                    out.write('#include "%s.h"\n#include <lib/thread.h>\n#include <recomp.h>\n#include <native.h>\n\n'
                              'namespace %s\n{\n\n' % (self.name, self.name))
                    for fn in functions[index:index + FUNCTIONS_PER_FILE]:
                        emit.write_entry(out, h, self.module, self.program, fn, self.function_name(fn.entry_address),
                                         'Application::', '    static ', 'WinApplication', self.function_names)
                    out.write('}\n')
            h.write('};\n\n}\n\n#endif /* !%s */\n' % guard)
        self.write_registration(functions)

    def write_registration(self, functions):
        imports = self.module.image.imports
        dlls = sorted(set(i.dll for i in imports))
        with open(self.path('%s.cpp' % self.name), 'w', newline='\n') as src:
            src.write('// Generated by tools/recompiler: method registration and import binding.\n'
                      '#include "%s.h"\n#include "%s_layout.h"\n#include <winapi/wrapper.h>\n' % (self.name, self.name))
            for dll in dlls:
                src.write('#include <winapi/%s.h>\n' % dll)
            src.write('\nnamespace %s\n{\n\n' % self.name)
            src.write('Application::Application(const char* appName, const std::vector<win32::Section>& sections)\n'
                      '    :   WinApplication(appName, layout::imageBase, sections)\n{\n')
            for fn in functions:
                name = self.function_name(fn.entry_address)
                src.write('    registerMethod(0x%08x, {"%s", &Application::%s});\n' % (fn.entry_address, name, name))
            src.write('    // Imports: the import address table slots point at fake addresses with the shims behind them.\n')
            for i in imports:
                function = 'win32::%s::%s' % (i.dll, cpp_name(i.name))
                src.write('    getMemory<x86::reg32>(0x%08x) = 0x%08x;\n' % (i.iat_address, i.fake_address))
                src.write('    registerMethod(0x%08x, {"<%s>%s", &win32::Wrapper<decltype(&%s), &%s>::stdcall});\n'
                          % (i.fake_address, i.dll, i.name, function, function))
            src.write('}\n\nvoid Application::execute()\n{\n    runThread(m_cpu, 0x%x);\n}\n\n}\n'
                      % self.module.entry_point)

    def write_layout(self):
        image = self.module.image
        guard = '%s_LAYOUT_H_' % self.name.upper()
        resources = [s for s in image.sections if s.name == '.rsrc']
        lines = ['// Generated by tools/recompiler: guest layout and identity of the game executable.',
                 '#ifndef %s' % guard, '#define %s' % guard, '#include <x86.h>', '',
                 'namespace %s { namespace layout {' % self.name, '',
                 '// The executable the code was generated from; the runtime loads only this file.',
                 'constexpr const char* exeSha256 = "%s";' % image.sha256,
                 'constexpr x86::reg32 exeSize = %d;' % len(image.file_bytes), '',
                 'constexpr x86::reg32 imageBase = 0x%x;' % image.base,
                 'constexpr x86::reg32 headerSize = 0x%x;' % image.header_size,
                 'constexpr x86::reg32 entryPoint = 0x%x;' % image.entry_point,
                 '// End of the highest section; the guest heap starts above it.',
                 'constexpr x86::reg32 imageEnd = 0x%x;' % image.end_address(),
                 'constexpr x86::reg32 resourceSection = 0x%x;' % (resources[0].address if resources else 0), '',
                 'struct ImageSection',
                 '{',
                 '    const char* name;',
                 '    x86::reg32  address;',
                 '    x86::reg32  virtualSize;',
                 '    x86::reg32  fileOffset;     // raw data in the file',
                 '    x86::reg32  rawSize;',
                 '};', '',
                 'constexpr ImageSection sections[] = {']
        for s in image.sections:
            lines.append('    { "%s", 0x%x, 0x%x, 0x%x, 0x%x },' % (s.name, s.address, s.virtual_size, s.file_offset,
                                                                    s.raw_size))
        lines += ['};', '', '}}', '', '#endif /* !%s */' % guard, '']
        with open(self.path('%s_layout.h' % self.name), 'w', newline='\n') as f:
            f.write('\n'.join(lines))
